#include <iostream>
#include <queue>
#include <stack>
#include <vector>
using namespace std;

class Solution {
public:
    int m, n;

    int numIslands(vector<vector<char>> &grid) {
        m = grid.size();
        n = grid[0].size();

        int count = 0;
        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                if (grid[i][j] == '1') {
                    grid[i][j] = '2';
                    explore(i, j, grid);
                    count++;
                }
            }
        }
        return count;
    }

    void explore(int i, int j, vector<vector<char>> &g) {
        stack<pair<int, int>> s;
        s.emplace(i, j);
        while (!s.empty()) {
            auto y = s.top().first;
            auto x = s.top().second;
            s.pop();

            bool u = y > 0, d = y < m - 1, l = x > 0, r = x < n - 1;
            if (u && g[y - 1][x] == '1') {
                g[y - 1][x] = '2';
                s.emplace(y - 1, x);
            }
            if (d && g[y + 1][x] == '1') {
                g[y + 1][x] = '2';
                s.emplace(y + 1, x);
            }
            if (l && g[y][x - 1] == '1') {
                g[y][x - 1] = '2';
                s.emplace(y, x - 1);
            }
            if (r && g[y][x + 1] == '1') {
                g[y][x + 1] = '2';
                s.emplace(y, x + 1);
            }
        }
    }
};

